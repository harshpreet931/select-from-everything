-- events: an append-only log. windows, gaps and islands, time zones, BRIN, partitioning, jsonb.

CREATE TABLE events (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     int NOT NULL,
  kind        text NOT NULL CHECK (kind IN ('signup','view','click','add_to_cart','purchase')),
  occurred_at timestamptz NOT NULL,
  amount      numeric(10,2),
  props       jsonb NOT NULL DEFAULT '{}',
  CHECK ((kind = 'purchase') = (amount IS NOT NULL))
);
