-- bank: accounts and the transfers between them. balance is a cached sum on purpose
-- (opening_balance + money in - money out), so a chapter can prove it and then break it.

CREATE TABLE accounts (
  id              int PRIMARY KEY,
  owner           text NOT NULL,
  opening_balance numeric(12,2) NOT NULL,
  balance         numeric(12,2) NOT NULL CHECK (balance >= 0),
  currency        char(3) NOT NULL DEFAULT 'EUR',
  version         int NOT NULL DEFAULT 0,
  opened_at       timestamptz NOT NULL
);

CREATE TABLE transfers (
  id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_id int NOT NULL REFERENCES accounts,
  to_id   int NOT NULL REFERENCES accounts,
  amount  numeric(12,2) NOT NULL CHECK (amount > 0),
  sent_at timestamptz NOT NULL,
  CHECK (from_id <> to_id)
);
