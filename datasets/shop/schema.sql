-- shop: customers place orders, orders have line items, line items point at products.
-- only primary keys, UNIQUE and foreign keys. no secondary indexes on purpose: every index
-- chapter starts from "no index" and makes its own.

CREATE TABLE customers (
  id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  email       text UNIQUE,
  city        text,
  country     char(2) NOT NULL,
  created_at  timestamptz NOT NULL
);

CREATE TABLE products (
  id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku          text NOT NULL UNIQUE,
  name         text NOT NULL,
  category     text,
  price        numeric(10,2) NOT NULL CHECK (price >= 0),
  tags         text[] NOT NULL DEFAULT '{}',
  attrs        jsonb NOT NULL DEFAULT '{}',
  description  text,
  discontinued boolean NOT NULL DEFAULT false
);

CREATE TABLE orders (
  id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id int NOT NULL REFERENCES customers,
  status      text NOT NULL CHECK (status IN ('placed','paid','shipped','delivered','cancelled','refunded')),
  ordered_at  timestamptz NOT NULL,
  shipped_at  timestamptz,
  CHECK (shipped_at IS NULL OR shipped_at >= ordered_at)
);

CREATE TABLE order_items (
  order_id   int NOT NULL REFERENCES orders ON DELETE CASCADE,
  line_no    smallint NOT NULL,
  product_id int NOT NULL REFERENCES products,
  qty        int NOT NULL CHECK (qty > 0),
  unit_price numeric(10,2) NOT NULL,
  PRIMARY KEY (order_id, line_no)
);
