-- @title a teas table, filled one INSERT at a time, then three kinds of id column
-- @engine pglite
-- @each

-- the stepper and the id switch on writes/insert read these. the teas table is the chapter's
-- first CREATE TABLE, the same one its runnable blocks build on the empty database.

-- @step T1 "a brand new table: four columns, no rows."
CREATE TABLE teas (
  id     int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name   text NOT NULL,
  origin text,
  grams  int NOT NULL DEFAULT 100
);

-- @step T1 "empty. a table is just its columns until something goes in."
SELECT id, name, origin, grams FROM teas ORDER BY id;

-- @step T1 "one row. you named three columns; id came from the identity column's sequence."
INSERT INTO teas (name, origin, grams) VALUES ('assam', 'india', 250);

-- @step T1 "the table after it."
SELECT id, name, origin, grams FROM teas ORDER BY id;

-- @step T1 "three rows in one statement. nobody said grams, so each got the default, 100."
INSERT INTO teas (name, origin) VALUES
  ('sencha', 'japan'),
  ('darjeeling', 'india'),
  ('rooibos', 'south africa');

-- @step T1 "the table after it."
SELECT id, name, origin, grams FROM teas ORDER BY id;

-- @step T1 "DEFAULT asks for the default by name. origin has none, so NULL is its default."
INSERT INTO teas (name, origin, grams) VALUES ('house blend', DEFAULT, DEFAULT);

-- @step T1 "the table after it."
SELECT id, name, origin, grams FROM teas ORDER BY id;

-- @step T1 errors=23502 "no name, and name is NOT NULL. the whole statement fails and nothing is written."
INSERT INTO teas (origin) VALUES ('china');

-- @step T1 "the table after it: unchanged."
SELECT id, name, origin, grams FROM teas ORDER BY id;

-- @step T1 "a transaction. nothing inside it is real until COMMIT."
BEGIN;

-- @step T1 "pu-erh goes in, and takes the next id from the sequence."
INSERT INTO teas (name, origin, grams) VALUES ('pu-erh', 'china', 357);

-- @step T1 "inside the transaction, the row is there."
SELECT id, name, origin, grams FROM teas ORDER BY id;

-- @step T1 "ROLLBACK. the row goes, but the sequence never gives a number back."
ROLLBACK;

-- @step T1 "the table after it."
SELECT id, name, origin, grams FROM teas ORDER BY id;

-- @step T1 "the next insert gets 8. 6 went to the insert that failed, 7 to the one rolled back."
INSERT INTO teas (name, origin, grams) VALUES ('oolong', 'taiwan', 50);

-- @step T1 "the table after it: a gap at 6 and 7, for good."
SELECT id, name, origin, grams FROM teas ORDER BY id;

-- @step T1 errors=428C9 "GENERATED ALWAYS: the identity column refuses a value you typed. the mistake is caught on the spot."
CREATE TABLE kinds (id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY, name text);
INSERT INTO kinds (id, name) VALUES (1, 'typed by hand');
INSERT INTO kinds (name) VALUES ('from the sequence');

-- @step T1 "clean up for the next kind."
DROP TABLE kinds;

-- @step T1 errors=23505 "GENERATED BY DEFAULT takes the typed 1. the sequence doesn't know, hands out 1 next, and the second insert hits the primary key."
CREATE TABLE kinds (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text);
INSERT INTO kinds (id, name) VALUES (1, 'typed by hand');
INSERT INTO kinds (name) VALUES ('from the sequence');

-- @step T1 "clean up for the next kind."
DROP TABLE kinds;

-- @step T1 errors=23505 "serial does the same: a plain DEFAULT nextval(...), which a typed value simply skips."
CREATE TABLE kinds (id serial PRIMARY KEY, name text);
INSERT INTO kinds (id, name) VALUES (1, 'typed by hand');
INSERT INTO kinds (name) VALUES ('from the sequence');
